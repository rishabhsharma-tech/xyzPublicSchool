-- Run this in Supabase Dashboard > SQL Editor.
-- Keep access private: no anon/authenticated policies are created here.
CREATE TABLE IF NOT EXISTS public.admission_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name TEXT NOT NULL CHECK (char_length(student_name) BETWEEN 2 AND 120),
    date_of_birth DATE NOT NULL,
    gender TEXT NOT NULL CHECK (gender IN ('male', 'female', 'other')),
    class_applying_for TEXT NOT NULL,
    father_name TEXT NOT NULL,
    mother_name TEXT NOT NULL,
    phone TEXT NOT NULL CHECK (phone ~ '^[0-9]{10}$'),
    email TEXT,
    address TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    pincode TEXT NOT NULL CHECK (pincode ~ '^[0-9]{6}$'),
    previous_school TEXT,
    previous_class TEXT,
    declaration_accepted BOOLEAN NOT NULL DEFAULT TRUE CHECK (declaration_accepted = TRUE),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.admission_applications ENABLE ROW LEVEL SECURITY;
-- Intentionally no public SELECT/INSERT/UPDATE/DELETE policies.
-- Only the server-side secret key is used by server.js; never put it in browser code.
